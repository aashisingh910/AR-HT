// Puts the approved photo-generated models inside the app, so they work offline and need no hosting.
//   node scripts/bundle-models.mjs
// For every models/raw/<product id>.glb: orient it upright, fit it to the listed size and check it (same as `image-to-3d.mjs --normalise`).
// Models that pass are copied to assets/models/<id>.glb and listed in src/data/bundledModels.ts. Ones that need review are left out.
// At most --max (default 60) models go inside the app; the rest stay in models/published/ to be hosted (MODEL_BASE_URL + publish-models.mjs).
// To force one in anyway after you have looked at it: --accept <id>,<id>.  Remove a model: delete its file in assets/models and run again.
//   --top 160          only the 160 most important products (sample-room pieces first, then sofas, beds, ...: the order image-to-3d.mjs uses)
//   --max-stretch 1.8  also take REVIEW models whose only problem is a shape stretch up to 1.8x (they are still scaled to the exact real size)
import fs from 'node:fs';
import path from 'node:path';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { arReady, BACK_HEAVY, normalise } from './publish-models.mjs';
import { pickProducts } from './lib/image3d.mjs';

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);

const RAW = 'models/raw', OUT = 'assets/models', TMP = 'models/published';
const accept = new Set((process.argv.includes('--accept') ? process.argv[process.argv.indexOf('--accept') + 1] : '').split(',').filter(Boolean));
const flip = new Set((process.argv.includes('--flip') ? process.argv[process.argv.indexOf('--flip') + 1] : '').split(',').filter(Boolean)); // facing the wrong way
const MAX = Number((process.argv.includes('--max') ? process.argv[process.argv.indexOf('--max') + 1] : 60)); // the app download grows ~2 MB per bundled model
const catalogue = JSON.parse(fs.readFileSync('src/data/catalogue.json', 'utf8'));
const byId = new Map(catalogue.map((p) => [p.id, p]));
fs.mkdirSync(OUT, { recursive: true }); fs.mkdirSync(TMP, { recursive: true });

const arg = (n) => (process.argv.includes(`--${n}`) ? process.argv[process.argv.indexOf(`--${n}`) + 1] : undefined);
const TOP = arg('top') ? Number(arg('top')) : 0, MAX_STRETCH = Number(arg('max-stretch') ?? 0);
const rooms = JSON.parse(fs.readFileSync('src/data/rooms.json', 'utf8'));
const top = TOP ? pickProducts(catalogue, rooms, TOP).map((p) => p.id) : null;
const files = fs.readdirSync(RAW).filter((x) => x.endsWith('.glb') && !x.startsWith('_'));
// Most important first, so the size limit drops the least important products, not random ones.
const ordered = top ? top.map((id) => `${id}.glb`).filter((f) => files.includes(f)) : files;
if (top) console.log(`Top ${TOP} products: ${ordered.length} have a generated model, ${top.length - ordered.length} have not been generated yet (they keep the proxy shape)`);

const kept = [];
for (const f of ordered) {
  const id = f.slice(0, -4), p = byId.get(id);
  if (!p) { console.log('skip (not in the catalogue)', id); continue; }
  const out = path.join(TMP, f);
  const r = await normalise(path.join(RAW, f), out, p.dimensionsCm, flip.has(id) ? 180 : 0, { auto: true, role: p.role });
  const shapeOnly = r.issues.length > 0 && r.issues.every((i) => i.startsWith('shape is'));
  const ok = !r.issues.length || (shapeOnly && (accept.has(id) || (MAX_STRETCH && r.stretch <= MAX_STRETCH)));
  console.log(`${ok ? 'BUNDLE' : 'REVIEW'} ${id}  stretch ${r.stretch.toFixed(2)}x  ${r.issues.join('; ')}`);
  if (ok && kept.length < MAX) { fs.copyFileSync(out, path.join(OUT, f)); kept.push(id); }
  else if (ok) console.log('  (passed, but the app already holds', MAX, 'models: host this one instead, see docs/DEPLOY.md)');
}
// anything already bundled stays bundled; ones with no raw source get the same AR fixes in place (idempotent: baked, normals, material, facing)
for (const f of fs.readdirSync(OUT).filter((x) => x.endsWith('.glb'))) {
  const id = f.slice(0, -4);
  if (kept.includes(id)) continue;
  kept.push(id);
  const doc = await io.read(path.join(OUT, f));
  const { turned } = await arReady(doc, { backHeavy: !flip.has(id) && BACK_HEAVY.has(byId.get(id)?.role) });
  await io.write(path.join(OUT, f), doc);
  console.log(`KEPT   ${id}  (no raw file: made AR-ready in place${turned ? ', turned 180' : ''})`);
}
kept.sort();
const lines = kept.map((id) => `  '${id}': require('../../assets/models/${id}.glb'),`).join('\n');
fs.writeFileSync('src/data/bundledModels.ts', `// Generated by scripts/bundle-models.mjs. Do not edit.\n/* eslint-disable */\nexport const BUNDLED_MODELS: Record<string, number> = {\n${lines}\n};\n`);
console.log(`${kept.length} model(s) bundled in src/data/bundledModels.ts`);
